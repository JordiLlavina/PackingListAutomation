-- Hojas de corte de un modelo (Documentos del Corte → «Hoja de corte»).
--
-- hoja_corte guarda cada hoja generada, con el patrón de hoja_produccion: las
-- columnas sueltas son las que se listan en la pantalla de antiguas y `datos`
-- es el snapshot entero (JSON de DatosHojaCorte), para regenerar lo que de
-- verdad se imprimió aunque el catálogo haya cambiado después. `foto`: la
-- subida en el formulario (JPEG ya reducido), o null si la hoja usa la
-- principal del modelo en el catálogo. Sin numeración: la hoja no sale de casa.
--
-- No mueve datos. SQL del subconjunto común a H2 y PostgreSQL, como desde la V4.

create table hoja_corte (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    temporada varchar(60),
    modelo varchar(80),
    nombre_bolso varchar(200),
    colores integer not null,
    fecha timestamp(6) not null,
    datos clob not null,                 -- JSON de DatosHojaCorte: lo que se imprimió
    foto bytea,
    primary key (id)
);
