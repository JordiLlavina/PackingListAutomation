-- Esquema que hasta hoy creaba Hibernate con ddl-auto: update.
-- A partir de aquí el esquema lo mandan las migraciones.
--
-- Vive en db/migration/h2 y no en common porque el excel de pedido de una
-- temporada se guarda entero en la base de datos y el tipo binario difiere:
-- BLOB en H2, BYTEA en PostgreSQL. El plan de publicación escribe su gemelo
-- en db/migration/postgresql y ninguna otra migración necesita partirse.
--
-- Es el DDL que Hibernate generaba de verdad (volcado con SCRIPT NODATA
-- sobre la base de datos que creaba), no uno escrito de memoria: las
-- longitudes y los NOT NULL son los de las anotaciones de las entidades.

create table tara_caja (
    medida               varchar(40)      not null,
    tara_kg              double precision not null,
    fecha_actualizacion  timestamp        not null,
    primary key (medida)
);

create table memoria_caja_referencia (
    cliente              varchar(60)      not null,
    referencia           varchar(80)      not null,
    medida_caja          varchar(40)      not null,
    unidades_por_caja    integer          not null,
    peso_neto_kg         double precision,
    fecha_actualizacion  timestamp        not null,
    primary key (cliente, referencia)
);

create table temporada_guardada (
    id                   bigint generated by default as identity,
    cliente              varchar(60)  not null,
    temporada            varchar(60)  not null,
    nombre_fichero       varchar(255) not null,
    excel                blob         not null,
    fecha_actualizacion  timestamp    not null,
    primary key (id),
    constraint uk_temporada_por_cliente unique (cliente, temporada)
);
