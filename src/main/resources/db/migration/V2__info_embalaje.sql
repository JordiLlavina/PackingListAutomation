-- Etiqueta «Info de embalaje» para el taller.
--
-- hoja_embalaje guarda cada hoja generada. Las columnas sueltas son las que se
-- listan y se filtran (pantalla de antiguos, siguiente nº de envío, última hoja
-- de un modelo); `datos` es el snapshot entero (JSON de DatosHojaEmbalaje) y es
-- un clob porque tiene que enseñar lo que de verdad se imprimió: dentro de un
-- año el excel de la temporada o la memoria del artículo pueden haber cambiado.
-- La foto no va dentro: se vuelve a buscar en el catálogo por codigo_modelo.
--
-- comentario_embalaje son los comentarios tipo que el usuario añade a la hoja
-- desde un desplegable; el nombre es único.

create table hoja_embalaje (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    temporada varchar(60) not null,
    temporada_id bigint,                 -- sin FK: si la temporada se borra, la hoja se queda
    numero_envio integer not null,
    nota varchar(60),
    taller varchar(60),
    referencia varchar(80) not null,
    codigo_color varchar(200) not null,
    codigo_modelo varchar(80),           -- para «última hoja del modelo» y la foto
    fecha timestamp(6) not null,
    datos clob not null,                 -- JSON de DatosHojaEmbalaje: lo que se imprimió
    primary key (id)
);

create table comentario_embalaje (
    id bigint generated by default as identity,
    nombre varchar(100) not null,
    texto varchar(4000) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint uk_comentario_embalaje_nombre unique (nombre)
);
