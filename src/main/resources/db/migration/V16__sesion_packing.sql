-- Sesiones guardadas del asistente de packing list.
--
-- sesion_packing guarda cada envío tal como está en la pantalla de revisión,
-- para volver a él días después (botón «Cargar Sesión» de /packing-list). Las
-- columnas sueltas son las que se listan (cliente, fecha de creación y lo
-- justo para reconocerla); `datos` es el envío entero (JSON de
-- SesionPackingDatos) y `excel_pedido` el excel de pedido con el que se
-- importó, que hace falta para regenerar las etiquetas de caja.
--
-- No mueve datos. SQL del subconjunto común a H2 y PostgreSQL, como desde la
-- V4, y los binarios como bytea.

create table sesion_packing (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    temporada varchar(60),
    facturas varchar(400),
    destinos varchar(1000),
    creada timestamp(6) not null,
    modificada timestamp(6) not null,
    datos clob not null,                 -- JSON de SesionPackingDatos: el envío de la revisión
    excel_pedido bytea,
    nombre_excel_pedido varchar(255),
    primary key (id)
);

create index ix_sesion_packing_cliente on sesion_packing (cliente);
