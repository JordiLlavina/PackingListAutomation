-- Esquema de la aplicación. Es la única migración: cuando se escribió, la
-- aplicación no estaba desplegada y la base de ./datos se borró y se creó de
-- cero con ella (los tests la crean en memoria en cada arranque). Hibernate
-- corre con ddl-auto: validate, así que un desajuste entre una entidad y
-- este fichero rompe el primer @SpringBootTest.
--
-- A partir de que la aplicación esté en uso, cualquier cambio de esquema va
-- en una migración nueva (V2__...) con su migración de datos: nada de lo que
-- se recuerda se pierde.

create table tara_caja (
    medida varchar(40) not null,
    tara_kg float(53) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (medida)
);

create table temporada_guardada (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    temporada varchar(60) not null,
    nombre_fichero varchar(255) not null,
    excel blob not null,
    tipo_excel varchar(20) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint uk_temporada_por_cliente unique (cliente, temporada)
);

create table color_cliente (
    cliente varchar(60) not null,
    codigo varchar(40) not null,
    descripcion varchar(200) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (cliente, codigo)
);

-- Catálogo de modelos: modelo (la forma del bolso) → artículo (modelo + piel,
-- la referencia entera del cliente) → artículo en un color del bolso. Las FK
-- son del SQL y no de las entidades (columnas planas, como el resto): borrar
-- un modelo se lleva sus artículos, colores, fotos y temporadas; borrar una
-- piel deja el artículo sin piel.
create table piel (
    cliente varchar(60) not null,
    ref_piel varchar(80) not null,
    nombre varchar(200) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (cliente, ref_piel)
);

create table modelo (
    cliente varchar(60) not null,
    codigo varchar(80) not null,
    nombre varchar(200),
    tipo varchar(20) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (cliente, codigo)
);

create table articulo (
    cliente varchar(60) not null,
    referencia varchar(80) not null,
    codigo_modelo varchar(80) not null,
    ref_piel varchar(80),
    forro varchar(200),
    combinacion1 varchar(200),
    combinacion2 varchar(200),
    combinacion3 varchar(200),
    combinacion4 varchar(200),
    medida_caja varchar(40),
    unidades_por_caja integer,
    peso_neto_kg float(53),
    fecha_actualizacion timestamp(6) not null,
    primary key (cliente, referencia),
    constraint fk_articulo_modelo foreign key (cliente, codigo_modelo)
        references modelo (cliente, codigo) on delete cascade,
    constraint fk_articulo_piel foreign key (cliente, ref_piel)
        references piel (cliente, ref_piel) on delete set null
);

-- codigo_color es el código del color del bolso o, si no tiene, su
-- descripción entera (el bicolor de AMI, los de un genérico): por eso es
-- largo y no lleva FK a color_cliente.
create table articulo_color (
    cliente varchar(60) not null,
    referencia varchar(80) not null,
    codigo_color varchar(200) not null,
    color_piel varchar(200),
    color_forro varchar(200),
    color_combinacion1 varchar(200),
    color_combinacion2 varchar(200),
    color_combinacion3 varchar(200),
    color_combinacion4 varchar(200),
    fecha_actualizacion timestamp(6) not null,
    primary key (cliente, referencia, codigo_color),
    constraint fk_articulo_color_articulo foreign key (cliente, referencia)
        references articulo (cliente, referencia) on delete cascade
);

create table foto_modelo (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    codigo_modelo varchar(80) not null,
    nombre_fichero varchar(255) not null,
    principal boolean not null,
    orden integer not null,
    bytes blob not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint fk_foto_modelo foreign key (cliente, codigo_modelo)
        references modelo (cliente, codigo) on delete cascade
);

create table modelo_temporada (
    cliente varchar(60) not null,
    codigo_modelo varchar(80) not null,
    temporada_id bigint not null,
    primary key (cliente, codigo_modelo, temporada_id),
    constraint fk_modelo_temporada_modelo foreign key (cliente, codigo_modelo)
        references modelo (cliente, codigo) on delete cascade,
    constraint fk_modelo_temporada_temporada foreign key (temporada_id)
        references temporada_guardada (id) on delete cascade
);
