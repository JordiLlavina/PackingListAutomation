-- App de modelos y modificaciones (segunda aplicación dentro del mismo jar).
-- Es la primera migración que, además de cambiar lo existente, crea tablas
-- nuevas de esa aplicación: usuarios, dispositivos, modificaciones, mensajes,
-- adjuntos, documentos, avisos push...
--
-- 1. El modelo pasa a tener id interno. Hasta aquí su clave era
--    (cliente, codigo), pero un prototipo todavía no tiene código del cliente,
--    y el código puede cambiar cuando lo tenga (queda en modelo_codigo_historico).
--    Para dar identidad a una tabla que ya existe no se añade una columna
--    identity (cada motor lo hace a su manera): se crea una tabla nueva con su
--    id, se vuelcan las filas, se recolocan los hijos con una subconsulta
--    correlacionada y se borra la vieja. Eso se escribe igual en H2 y en
--    PostgreSQL.
--
-- 2. Dialecto: desde esta migración el SQL es el subconjunto común a H2 y a
--    PostgreSQL, por si algún día se cambia de motor. Tipos: bigint generated
--    by default as identity, varchar(n), text, bytea, timestamp, boolean.
--    Cambios de esquema: alter table ... rename column / rename to, alter
--    column ... set not null / drop not null, drop constraint. Nada de jsonb,
--    arrays, serial, on update cascade, índices parciales ni blob. (Las
--    columnas blob que ya existían, como foto_modelo.bytes, se quedan como
--    están: cambiarlas es otra migración.)
--
-- Nada de lo guardado se pierde: los modelos existentes quedan en etapa
-- PRODUCCION, con su código, y sus artículos, fotos y temporadas apuntan a su
-- nuevo id.

-- Modelo -----------------------------------------------------------------

create table modelo_v4 (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    codigo varchar(80),                      -- null mientras es un prototipo sin código
    nombre_prototipo varchar(200),           -- el nombre con el que se conoce antes de tener código
    nombre varchar(200),
    tipo varchar(20) not null,
    etapa varchar(20) not null,
    fecha_etapa timestamp(6) not null,
    temporada_alta_id bigint,                -- la temporada en que nació el prototipo
    etiqueta_impresa_en timestamp(6),
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint uk_modelo_codigo unique (cliente, codigo),
    constraint uk_modelo_prototipo unique (cliente, nombre_prototipo, temporada_alta_id),
    constraint ck_modelo_identidad check (codigo is not null or nombre_prototipo is not null),
    constraint fk_modelo_temporada_alta foreign key (temporada_alta_id)
        references temporada_guardada (id) on delete set null
);

insert into modelo_v4 (cliente, codigo, nombre, tipo, etapa, fecha_etapa, fecha_actualizacion)
select cliente, codigo, nombre, tipo, 'PRODUCCION', fecha_actualizacion, fecha_actualizacion
  from modelo;

-- Artículo ----------------------------------------------------------------

alter table articulo add column modelo_id bigint;

update articulo
   set modelo_id = (select m.id from modelo_v4 m
                     where m.cliente = articulo.cliente and m.codigo = articulo.codigo_modelo);

alter table articulo drop constraint fk_articulo_modelo;
alter table articulo drop column codigo_modelo;
alter table articulo alter column modelo_id set not null;

-- Fotos -------------------------------------------------------------------

alter table foto_modelo add column modelo_id bigint;

update foto_modelo
   set modelo_id = (select m.id from modelo_v4 m
                     where m.cliente = foto_modelo.cliente and m.codigo = foto_modelo.codigo_modelo);

alter table foto_modelo drop constraint fk_foto_modelo;
alter table foto_modelo drop column cliente;
alter table foto_modelo drop column codigo_modelo;
alter table foto_modelo alter column modelo_id set not null;

-- Modelo y temporada (N:M) --------------------------------------------------
-- Su clave primaria llevaba el código, así que se rehace entera.

create table modelo_temporada_v4 (
    modelo_id bigint not null,
    temporada_id bigint not null,
    primary key (modelo_id, temporada_id)
);

insert into modelo_temporada_v4 (modelo_id, temporada_id)
select m.id, mt.temporada_id
  from modelo_temporada mt
  join modelo_v4 m on m.cliente = mt.cliente and m.codigo = mt.codigo_modelo;

drop table modelo_temporada;
alter table modelo_temporada_v4 rename to modelo_temporada;

-- Sustituir la tabla vieja ----------------------------------------------------
-- Ya nada referencia a modelo (articulo, foto_modelo y modelo_temporada
-- soltaron sus claves ajenas arriba).

drop table modelo;
alter table modelo_v4 rename to modelo;

alter table articulo add constraint fk_articulo_modelo foreign key (modelo_id)
    references modelo (id) on delete cascade;
alter table foto_modelo add constraint fk_foto_modelo foreign key (modelo_id)
    references modelo (id) on delete cascade;
alter table modelo_temporada add constraint fk_modelo_temporada_modelo foreign key (modelo_id)
    references modelo (id) on delete cascade;
alter table modelo_temporada add constraint fk_modelo_temporada_temporada foreign key (temporada_id)
    references temporada_guardada (id) on delete cascade;

-- Tablas nuevas de la app de modelos --------------------------------------------
-- En el orden de sus claves ajenas: usuario primero.

create table usuario (
    id bigint generated by default as identity,
    nombre varchar(120) not null,
    login varchar(80),
    password_hash varchar(200),
    correo varchar(200),
    oid_entra varchar(80),                   -- identificador del usuario en Microsoft Entra
    rol varchar(20) not null,
    activo boolean not null default true,
    fecha_alta timestamp(6) not null,
    ultimo_acceso timestamp(6),
    primary key (id),
    constraint uk_usuario_login unique (login),
    constraint uk_usuario_oid_entra unique (oid_entra)
);

create table dispositivo (
    id bigint generated by default as identity,
    usuario_id bigint not null,
    nombre varchar(120) not null,
    token_hash varchar(100) not null,
    alta timestamp(6) not null,
    ultimo_uso timestamp(6),
    revocado_en timestamp(6),
    primary key (id),
    constraint uk_dispositivo_token unique (token_hash),
    constraint fk_dispositivo_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade
);

create table codigo_alta (
    id bigint generated by default as identity,
    usuario_id bigint not null,
    codigo varchar(6) not null,
    caduca timestamp(6) not null,
    usado_en timestamp(6),
    primary key (id),
    constraint fk_codigo_alta_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade
);

create table suscripcion_push (
    id bigint generated by default as identity,
    usuario_id bigint not null,
    dispositivo_id bigint,
    endpoint text not null,
    p256dh varchar(200) not null,
    auth varchar(100) not null,
    fecha timestamp(6) not null,
    primary key (id),
    constraint fk_suscripcion_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade,
    constraint fk_suscripcion_dispositivo foreign key (dispositivo_id)
        references dispositivo (id) on delete cascade
);

create table modelo_codigo_historico (
    id bigint generated by default as identity,
    modelo_id bigint not null,
    codigo varchar(80) not null,
    desde timestamp(6) not null,
    hasta timestamp(6),
    motivo varchar(200),
    primary key (id),
    constraint fk_codigo_historico_modelo foreign key (modelo_id)
        references modelo (id) on delete cascade
);

create table cambio_etapa (
    id bigint generated by default as identity,
    modelo_id bigint not null,
    de varchar(20),                          -- null en el primer apunte del modelo
    a varchar(20) not null,
    fecha timestamp(6) not null,
    usuario_id bigint,
    motivo varchar(200),
    primary key (id),
    constraint fk_cambio_etapa_modelo foreign key (modelo_id)
        references modelo (id) on delete cascade,
    constraint fk_cambio_etapa_usuario foreign key (usuario_id)
        references usuario (id)
);

create table documento_modelo (
    id bigint generated by default as identity,
    modelo_id bigint not null,
    nombre varchar(255) not null,
    mime varchar(100) not null,
    tamano bigint not null,
    bytes bytea not null,
    subido_por bigint,
    fecha timestamp(6) not null,
    primary key (id),
    constraint fk_documento_modelo foreign key (modelo_id)
        references modelo (id) on delete cascade,
    constraint fk_documento_subido_por foreign key (subido_por)
        references usuario (id)
);

create table modificacion (
    id bigint generated by default as identity,
    modelo_id bigint not null,
    direccion varchar(20) not null,          -- despacho a taller o taller a despacho
    tipo_cambio varchar(40),
    prioridad varchar(20),
    estado varchar(20) not null,
    titulo varchar(200),
    titulo_de_ia boolean not null default false,
    necesita_respuesta boolean not null default false,
    creada_por bigint,
    creada_en timestamp(6) not null,
    vista_en timestamp(6),
    hecha_por bigint,
    hecha_en timestamp(6),
    motivo_descarte text,
    primary key (id),
    constraint fk_modificacion_modelo foreign key (modelo_id)
        references modelo (id) on delete cascade,
    constraint fk_modificacion_creada_por foreign key (creada_por)
        references usuario (id),
    constraint fk_modificacion_hecha_por foreign key (hecha_por)
        references usuario (id)
);

-- Solo existe en las modificaciones taller a despacho (lo garantiza el servicio).
create table modificacion_destino (
    id bigint generated by default as identity,
    modificacion_id bigint not null,
    destino varchar(40) not null,
    aplica boolean not null default true,
    hecho_en timestamp(6),
    hecho_por bigint,
    primary key (id),
    constraint fk_destino_modificacion foreign key (modificacion_id)
        references modificacion (id) on delete cascade,
    constraint fk_destino_hecho_por foreign key (hecho_por)
        references usuario (id)
);

create table mensaje (
    id bigint generated by default as identity,
    modificacion_id bigint not null,
    autor_id bigint,
    texto text,
    creado_en timestamp(6) not null,
    primary key (id),
    constraint fk_mensaje_modificacion foreign key (modificacion_id)
        references modificacion (id) on delete cascade,
    constraint fk_mensaje_autor foreign key (autor_id)
        references usuario (id)
);

create table adjunto (
    id bigint generated by default as identity,
    mensaje_id bigint not null,
    tipo varchar(20) not null,
    nombre varchar(255) not null,
    mime varchar(100) not null,
    tamano bigint not null,
    duracion_seg integer,                    -- solo audio y vídeo
    bytes bytea not null,
    transcripcion text,
    resumen_ia text,
    estado_transcripcion varchar(20),
    error text,
    fecha timestamp(6) not null,
    primary key (id),
    constraint fk_adjunto_mensaje foreign key (mensaje_id)
        references mensaje (id) on delete cascade
);

create table aviso_enviado (
    id bigint generated by default as identity,
    modificacion_id bigint not null,
    usuario_id bigint not null,
    tipo varchar(40) not null,
    enviado_en timestamp(6) not null,
    primary key (id),
    constraint fk_aviso_modificacion foreign key (modificacion_id)
        references modificacion (id) on delete cascade,
    constraint fk_aviso_usuario foreign key (usuario_id)
        references usuario (id)
);
