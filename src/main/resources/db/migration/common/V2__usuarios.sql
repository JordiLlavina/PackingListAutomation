-- Una fila por persona del directorio que ha entrado alguna vez.
--
-- La clave es el oid del directorio y no el correo: el correo cambia (alguien
-- cambia de apellido o de nombre de usuario) y ese día la persona entraría
-- como usuario nuevo sin permisos, con su histórico huérfano a nombre de una
-- dirección que ya no existe.
--
-- Los usuarios no se borran, se desactivan: borrar la fila deja el histórico
-- de actividad apuntando a un id que ya no existe, y el histórico es
-- justamente lo que se quiere conservar.
create table usuario (
    id             bigint       generated by default as identity,
    oid_entra      varchar(64)  not null,
    correo         varchar(255) not null,
    nombre         varchar(255) not null,
    administrador  boolean      not null default false,
    activo         boolean      not null default true,
    fecha_alta     timestamp with time zone not null,
    ultimo_acceso  timestamp with time zone,
    primary key (id),
    constraint uk_usuario_oid unique (oid_entra)
);
