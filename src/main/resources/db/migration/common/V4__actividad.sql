-- Qué se ha hecho con la aplicación. Metadatos de uso, nunca el contenido de
-- los documentos ni de los ficheros subidos.
--
-- No se purga: a unos pocos miles de eventos al año la tabla no es un
-- problema, y borrar el histórico es exactamente lo contrario de lo que se
-- quiere de él.
create table evento_actividad (
    id          bigint      generated by default as identity,
    usuario_id  bigint,
    -- Copia a propósito: el informe de hace un año tiene que seguir diciendo
    -- quién era esa persona entonces, y el correo del directorio cambia.
    correo      varchar(255) not null,
    momento     timestamp with time zone not null,
    seccion     varchar(32),
    tipo        varchar(48)  not null,
    cliente     varchar(64),
    cantidad    integer,
    detalle     varchar(500),
    primary key (id),
    constraint fk_evento_usuario foreign key (usuario_id) references usuario (id)
);

-- Los tres que necesita el dashboard: por fecha, por persona y por tipo.
-- Sin ellos, a los dos años la pantalla tardaría segundos sin necesidad.
create index ix_evento_momento on evento_actividad (momento);
create index ix_evento_usuario_momento on evento_actividad (usuario_id, momento);
create index ix_evento_tipo_momento on evento_actividad (tipo, momento);
