-- Biblioteca de pieles: lo que se sabe de cada piel y de su proveedor.
--
-- `piel` (la de siempre) dice cómo llama un CLIENTE a una piel: cliente +
-- referencia + nombre. `ficha_piel` dice qué piel ES: proveedor + nombre, con
-- sus precios, fotos, documentos y recorrido. La misma piel se usa para varios
-- clientes con referencias distintas, así que varias filas de `piel` pueden
-- apuntar a la misma ficha por `ficha_piel_id`, que es opcional: una piel que
-- entra desde producción sin más que su nombre se queda sin ficha y nada de lo
-- que ya había cambia.
--
-- No mueve datos: nada de lo guardado se pierde. SQL del subconjunto común a
-- H2 y PostgreSQL, como desde la V4, y los binarios como bytea.

create table proveedor (
    id bigint generated by default as identity,
    nombre varchar(200) not null,
    contacto varchar(200),
    email varchar(200),
    telefono varchar(60),
    pais varchar(80),
    condiciones varchar(1000),           -- pago, Incoterm, portes: texto libre
    responsabilidad integer,             -- 1-5: calidad del servicio, cuánto tarda en responder
    entrega_a_tiempo integer,            -- 1-5
    nota_valoracion varchar(2000),       -- una sola nota que se va corrigiendo
    fecha_valoracion timestamp(6),
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint uk_proveedor_nombre unique (nombre)
);

create table ficha_piel (
    id bigint generated by default as identity,
    proveedor_id bigint not null,
    nombre varchar(200) not null,
    ref_proveedor varchar(80),
    animal varchar(40),
    tipo varchar(60),
    grueso_min_mm double precision,      -- un valor fijo es mínimo = máximo
    grueso_max_mm double precision,
    superficie_min_m2 double precision,
    superficie_max_m2 double precision,
    stock_service boolean,               -- null: no se sabe
    plazo_entrega_dias integer,
    moq_por_color boolean,               -- el mínimo es de cada color y no del pedido entero
    fecha_precios date,                  -- de qué fecha es la oferta de los tramos
    calidad integer,                     -- 1-5
    nota_calidad varchar(1000),
    comentarios varchar(4000),
    origen varchar(20) not null,         -- MANUAL, FICHA, AGENTE
    fecha_alta timestamp(6) not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint uk_ficha_piel_nombre unique (proveedor_id, nombre),
    -- Sin cascada: un proveedor con pieles no se borra.
    constraint fk_ficha_piel_proveedor foreign key (proveedor_id) references proveedor (id)
);

-- Los tramos de precio vigentes. El de menor mínimo es el MOQ de la piel; un
-- mínimo del que aún no se sabe el precio lleva el precio vacío.
create table precio_piel (
    id bigint generated by default as identity,
    ficha_piel_id bigint not null,
    moq_m2 double precision,
    precio_eur_m2 double precision,
    primary key (id),
    constraint fk_precio_piel_ficha foreign key (ficha_piel_id)
        references ficha_piel (id) on delete cascade
);

create table foto_piel (
    id bigint generated by default as identity,
    ficha_piel_id bigint not null,
    nombre_fichero varchar(255) not null,
    principal boolean not null,
    orden integer not null,
    bytes bytea not null,
    fecha_actualizacion timestamp(6) not null,
    primary key (id),
    constraint fk_foto_piel_ficha foreign key (ficha_piel_id)
        references ficha_piel (id) on delete cascade
);

-- Fichas técnicas y ofertas: el original del que salieron los datos.
create table documento_piel (
    id bigint generated by default as identity,
    ficha_piel_id bigint not null,
    nombre_fichero varchar(255) not null,
    mime varchar(120),
    tamano integer not null,
    bytes bytea not null,
    fecha timestamp(6) not null,
    primary key (id),
    constraint fk_documento_piel_ficha foreign key (ficha_piel_id)
        references ficha_piel (id) on delete cascade
);

-- El recorrido de la piel entre clientes, apuntado a mano. El modelo es texto
-- y no un enlace a `modelo`: al juntar allí un prototipo con su referencia, un
-- enlace se perdería sin avisar.
create table evento_piel (
    id bigint generated by default as identity,
    ficha_piel_id bigint not null,
    fecha date not null,
    cliente varchar(60) not null,
    tipo varchar(20) not null,           -- BUSCADA, MOSTRADA, MUESTRA, PROTOTIPO, SMS, PRODUCCION, DESCARTADA
    modelo varchar(200),
    nota varchar(2000),
    primary key (id),
    constraint fk_evento_piel_ficha foreign key (ficha_piel_id)
        references ficha_piel (id) on delete cascade
);

-- De una sola columna, así que ON DELETE SET NULL no tiene el problema de la
-- clave compuesta de articulo: borrar una ficha deja la piel del cliente como
-- estaba antes de enlazarla.
alter table piel add column ficha_piel_id bigint;
alter table piel add constraint fk_piel_ficha foreign key (ficha_piel_id)
    references ficha_piel (id) on delete set null;
