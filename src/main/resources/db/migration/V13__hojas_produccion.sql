-- Hojas de Producción para los talleres externos (Sweet Bag, C&C Leather…).
--
-- hoja_produccion guarda cada hoja generada. Las columnas sueltas son las que
-- se listan y se filtran (pantalla de antiguas, siguiente nº de hoja de cada
-- taller, talleres usados); `datos` es el snapshot entero (JSON de
-- DatosHojaProduccion), para que una hoja antigua enseñe y regenere lo que de
-- verdad se mandó al taller aunque el catálogo haya cambiado después.
--
-- No mueve datos. SQL del subconjunto común a H2 y PostgreSQL, como desde la V4.

create table hoja_produccion (
    id bigint generated by default as identity,
    cliente varchar(60) not null,
    temporada varchar(60),
    nombre_bolso varchar(200),
    taller varchar(60) not null,
    numero integer not null,
    fecha_salida date,
    fecha timestamp(6) not null,
    datos clob not null,                 -- JSON de DatosHojaProduccion: lo que se imprimió
    primary key (id)
);

create index ix_hoja_produccion_taller on hoja_produccion (taller);
